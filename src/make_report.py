def md(df, fmt=None, index=False):
    d = df.reset_index() if index else df
    cols = list(d.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in d.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("–" if np.isnan(v) else (fmt.get(c, "{:,.3f}") if fmt else "{:,.3f}").format(v))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def ci(k):
    lo, hi = CI[k]; return f"[{lo:,.0f}, {hi:,.0f}]"


